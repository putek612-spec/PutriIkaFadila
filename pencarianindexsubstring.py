#count()
text = "hello world hello world"
print(text.count("ello"))

#index()
text = "hello world hello world"
print(text.index("worl"))

#rindex()
text = "hello world hello world"
print(text.rindex("worl"))

#find()
text = "hello world hello world"
print(text.find("worl"))

#rfind()
text = "hello world hello world"
print(text.rfind("worl"))


