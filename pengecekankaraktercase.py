#Method islower()
print("hello python".islower())

print("Hello python".islower())

print("HELLO PYTHON".islower())

#Method istitle()
print("hello python".istitle())

print("Hello python".istitle())

print("HELLO PYTHON".istitle())

#Method isupper()
print("hello python".isupper())

print("Hello python".isupper())

print("HELLO PYTHON".isupper())
